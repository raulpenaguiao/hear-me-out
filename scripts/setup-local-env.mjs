#!/usr/bin/env node
// Creates .env.local for local development from the running local Supabase
// stack (`npm run db:start`) and freshly generated secrets.
//
// Usage: npm run env:local [-- --force] [-- --out .env.test]
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const force = args.includes("--force");
const outIndex = args.indexOf("--out");
const out = outIndex >= 0 ? args[outIndex + 1] : ".env.local";

if (existsSync(out) && !force) {
  console.error(`${out} already exists. Re-run with --force to overwrite.`);
  process.exit(1);
}

let status;
try {
  status = execFileSync("npx", ["supabase", "status", "-o", "env"], { encoding: "utf8" });
} catch {
  console.error("Could not read local Supabase status. Is it running? Try: npm run db:start");
  process.exit(1);
}

const vars = Object.fromEntries(
  status
    .split("\n")
    .map((line) => /^([A-Z_]+)="?(.*?)"?$/.exec(line.trim()))
    .filter(Boolean)
    .map((m) => [m[1], m[2]]),
);

const required = ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"];
for (const key of required) {
  if (!vars[key]) {
    console.error(`Missing ${key} in supabase status output.`);
    process.exit(1);
  }
}

const content = `# Generated by scripts/setup-local-env.mjs — local development only.
NEXT_PUBLIC_APP_URL=http://localhost:3000
NEXT_PUBLIC_SUPABASE_URL=${vars.API_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${vars.ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${vars.SERVICE_ROLE_KEY}
TOKEN_HASH_SECRET=${randomBytes(48).toString("base64url")}
TOKEN_ENCRYPTION_KEY=${randomBytes(32).toString("base64")}
STORAGE_DRIVER=local
LOCAL_STORAGE_DIR=.data/storage
AUDIO_DELIVERY_MODE=proxy
AUDIO_MAX_UPLOAD_MB=200
AUDIO_MAX_DURATION_MINUTES=180
COVER_MAX_UPLOAD_MB=5
RATE_LIMIT_ENABLED=true
TRUST_PROXY_HEADERS=false
`;

writeFileSync(out, content, { mode: 0o600 });
console.log(`Wrote ${out}`);
